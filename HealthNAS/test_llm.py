from backend.llm.llm_pipeline import HealthcareLLMPipeline
from backend.llm.embeddings import HealthcareEmbeddings
from backend.llm.tokenizer import HealthcareTokenizer


def main():

    print("\n")
    print("=" * 70)
    print("LLM-GUIDED NEURAL ARCHITECTURE SEARCH")
    print("DOMAIN: HEALTHCARE")
    print("=" * 70)

    # Get the healthcare ML problem from the user
    print("\nEnter your healthcare AI problem:")
    query = input("> ")

    # Demonstrate how the LLM tokenizer processes the input
    print("\n")
    print("=" * 70)
    print("TOKENIZATION DEMONSTRATION")
    print("=" * 70)

    try:
        tokenizer_demo = HealthcareTokenizer()
        tokenizer_demo.demonstrate(query)

    except Exception as error:
        print("\nTokenizer demonstration could not run:")
        print(error)
        print("\nContinuing with the main pipeline...")

    # Demonstrate text-to-vector conversion for RAG
    print("\n")
    print("=" * 70)
    print("RAG EMBEDDING DEMONSTRATION")
    print("=" * 70)

    try:
        embedding_demo = HealthcareEmbeddings()
        embedding_demo.demonstrate_embedding(query)

    except Exception as error:
        print("\nEmbedding demonstration could not run:")
        print(error)
        print("\nContinuing with the main pipeline...")

    # Initialize the complete RAG + LLM pipeline
    print("\n")
    print("=" * 70)
    print("STARTING HEALTHCARE LLM + RAG PIPELINE")
    print("=" * 70)

    pipeline = HealthcareLLMPipeline()

    # Run the main LLM-guided NAS process
    try:
        result = pipeline.process(query)

    except Exception as error:
        print("\n")
        print("=" * 70)
        print("PIPELINE ERROR")
        print("=" * 70)

        print(f"\n{type(error).__name__}: {error}")

        pipeline.close()
        return

    # Display the original user query
    print("\n")
    print("=" * 70)
    print("USER QUERY")
    print("=" * 70)

    print(result["query"])

    # Display the documents selected by RAG
    print("\n")
    print("=" * 70)
    print("RAG RETRIEVED HEALTHCARE KNOWLEDGE")
    print("=" * 70)

    for i, document in enumerate(
        result["retrieved_documents"],
        start=1
    ):
        print(f"\nDocument {i}")

        print(
            "Similarity Score: "
            f"{document['score']:.4f}"
        )

        print("\nContent:")
        print(document["document"].strip())

    # Get the validated architecture generated by Qwen
    architecture = result["architecture"]

    print("\n")
    print("=" * 70)
    print("FINAL LLM-GENERATED NAS SPECIFICATION")
    print("=" * 70)

    # Display basic problem information
    print(
        f"\nDomain:\n"
        f"{architecture.get('domain', 'Not specified')}"
    )

    print(
        f"\nTask:\n"
        f"{architecture.get('task', 'Not specified')}"
    )

    print(
        f"\nData Type:\n"
        f"{architecture.get('data_type', 'Not specified')}"
    )

    print(
        f"\nProblem Type:\n"
        f"{architecture.get('problem_type', 'Not specified')}"
    )

    # Display the architecture search space
    print("\n")
    print("ARCHITECTURE SEARCH SPACE")
    print("-" * 70)

    search_space = architecture["search_space"]

    for parameter, values in search_space.items():
        print(f"\n{parameter}:")
        print(f"    {values}")

    # Display training configuration
    print("\n")
    print("TRAINING HYPERPARAMETERS")
    print("-" * 70)

    training = architecture.get("training", {})

    for parameter, value in training.items():
        print(f"\n{parameter}:")
        print(f"    {value}")

    # Display evaluation metrics
    print("\n")
    print("EVALUATION METRICS")
    print("-" * 70)

    metrics = architecture.get(
        "evaluation_metrics",
        []
    )

    for metric in metrics:
        print(f"✓ {metric}")

    # Display the reason generated by the LLM
    print("\n")
    print("LLM REASONING SUMMARY")
    print("-" * 70)

    print(
        architecture.get(
            "reason",
            "No reason provided."
        )
    )

    # Show that the generated search space is ready for NAS
    print("\n")
    print("=" * 70)
    print("LLM → NAS HANDOFF COMPLETE")
    print("=" * 70)

    print(
        """
The LLM has successfully:

✓ Analyzed the healthcare ML problem
✓ Used RAG-retrieved healthcare knowledge
✓ Generated architecture parameters
✓ Generated a NAS search space
✓ Returned structured JSON
✓ Passed search-space validation

The resulting search space is ready
for the NAS module.
"""
    )

    # Release resources before exiting
    pipeline.close()

    print("\n")
    print("=" * 70)
    print("LLM IMPLEMENTATION COMPLETE")
    print("=" * 70)


if __name__ == "__main__":
    main()